"""Generate the SEP type inventory, typed views and schema tables from the pinned XSD."""
import argparse
import hashlib
import json
import re
import subprocess
from pathlib import Path
from xml.etree import ElementTree as ET

XSD = "{http://www.w3.org/2001/XMLSchema}"
BASE_NS = "urn:ieee:std:2030.5:ns"
AUS_NS = "https://csipaus.org/ns"
PIN = "5b32e18378e64133e3a9f7f320ea10e204bb5596aac96898cdef9e8ec39a9164"
GENERATED = "// Generated by cargo xtask codegen.\n"
QUOTE = json.dumps


def snake(name):
    name = {"pIN": "PIN", "mRID": "MRID", "lFDI": "LFDI", "sFDI": "SFDI"}.get(name, name)
    words = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    words = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", words).lower()
    return "r#" + words if words in {"type", "ref", "match"} else words


def read_pinned(path, digest):
    try:
        data = path.read_bytes()
    except OSError as error:
        raise SystemExit(f"Cannot read {path}: {error.strerror}. See site/content/guides/schema.md for the required inputs.") from error
    if hashlib.sha256(data).hexdigest() != digest:
        raise SystemExit(f"{path.name} differs from the pinned release")
    return ET.fromstring(data)


def generate(schema, extras, overlays):
    lines = [GENERATED, "use super::*;"]
    arms = []
    roots = []
    named = []
    parents = {}
    for doc in [schema, *extras]:
        for node in doc:
            for tag in ("restriction", "extension"):
                parent = node.find(".//" + XSD + tag)
                if parent is not None:
                    parents[node.get("name")] = parent.get("base").removeprefix("bs:")
    integers = {"byte": "i8", "unsignedByte": "u8", "short": "i16", "unsignedShort": "u16",
                "int": "i32", "unsignedInt": "u32", "long": "i64", "unsignedLong": "u64"}
    for doc in [schema, *extras]:
        ns = doc.get("targetNamespace")
        ns_const = "SEP" if ns == BASE_NS else "AUS"
        cfg = "" if ns == BASE_NS else '#[cfg(feature = "csip-aus")] '
        for node in doc:
            name = node.get("name")
            if not name:
                continue
            if node.tag == XSD + "element":
                roots.append(f'{cfg}({ns_const}, "{name}") => Some("{node.attrib["type"].removeprefix("bs:")}"),')
                continue
            if node.tag not in {XSD + "complexType", XSD + "simpleType"}:
                raise ValueError(node.tag)
            named.append((ns, name))
            base = node.find(".//" + XSD + "extension")
            restriction = node.find(XSD + "restriction")
            if restriction is not None:
                base = restriction
            parent = "" if base is None else base.get("base").removeprefix("bs:")
            facets = {x.tag.removeprefix(XSD): x.get("value") for x in restriction} if restriction is not None else {}
            if facets.keys() - {"minInclusive", "maxInclusive", "maxLength"}:
                raise ValueError(facets)
            def facet(key):
                return f'Some({facets[key]})' if key in facets else "None"
            elements, attrs, methods = [], [], []
            for field in node.iter(XSD + "attribute"):
                key, typ = field.attrib["name"], field.attrib["type"]
                required = str(field.get("use") == "required").lower()
                default = field.get("default")
                default_expr = "" if default is None else f'.or(Some("{default}"))'
                attrs.append(f'Attribute {{ name: "{key}", ty: "{typ}", required: {required} }}')
                methods.append(f'pub fn {snake(key)}(&self) -> Option<&\'a str> {{ self.0.attribute("{key}"){default_expr} }}')
            fields = [(f, ns_const, "") for f in node.iter(XSD + "element")]
            fields.extend((f, "AUS", '#[cfg(feature = "csip-aus")] ') for f in overlays.get(name, []))
            for field, field_ns, field_cfg in fields:
                key = field.get("name") or field.attrib["ref"].split(":")[1]
                typ = field.get("type")
                if typ is None:
                    typ = next(d.attrib["type"] for root in extras for d in root.findall(XSD + "element") if d.get("name") == key)
                typ = typ.removeprefix("bs:")
                maximum = field.get("maxOccurs", "1")
                limit = "usize::MAX" if maximum == "unbounded" else maximum
                elements.append(f'{field_cfg}Member {{ ns: {field_ns}, name: "{key}", ty: "{typ}", min: {field.get("minOccurs", "1")}, max: {limit} }}')
                rust_type, convert = ("Node<'a, 'a>", "") if typ.startswith("xs:") else (f"{typ}<'a>", f".map({typ})")
                if maximum == "1":
                    signature, match_method = f"Option<{rust_type}>", "find"
                else:
                    signature, match_method = f"impl Iterator<Item = {rust_type}> + 'a", "filter"
                methods.append(f'{field_cfg}pub fn {snake(key)}(&self) -> {signature} {{ self.0.children().{match_method}(|n| n.has_tag_name(({field_ns}, "{key}"))){convert} }}')
            lines.extend([f'{cfg}view!({name});', f"{cfg}impl<'a> {name}<'a> {{"])
            if parent and not parent.startswith("xs:"):
                lines.append(f"pub fn as_base(&self) -> {parent}<'a> {{ {parent}(self.0) }}")
            primitive = parent
            while primitive in parents:
                primitive = parents[primitive]
            rust_int = integers.get(primitive.removeprefix("xs:"))
            if rust_int:
                methods.append(f"pub fn value(&self) -> {rust_int} {{ super::integer(self.0) }}")
            elif primitive == "xs:string":
                methods.append("pub fn value(&self) -> alloc::borrow::Cow<'a, str> { crate::codec::element_text(self.0) }")
            elif primitive == "xs:hexBinary":
                methods.append("pub fn bytes(&self) -> alloc::vec::Vec<u8> { super::hex(self.0) }")
            lines.extend(methods + ["}"])
            arms.append(f'{cfg}"{name}" => Some(("{name}", &Shape {{ ns: {ns_const}, base: "{parent}", attrs: &[{", ".join(attrs)}], members: &[{", ".join(elements)}], max_len: {facet("maxLength")}, min: {facet("minInclusive")}, max: {facet("maxInclusive")} }})),')
    lines.extend(['pub(crate) fn shape(name: &str) -> Option<&\'static Shape> { named_shape(name).map(|(_, s)| s) }', 'pub(crate) fn named_shape(name: &str) -> Option<(&\'static str, &\'static Shape)> { match name {', *arms, '_ => None, }}',
                  'pub(crate) fn root_type(ns: &str, name: &str) -> Option<&\'static str> { match (ns,name) {', *roots, '_ => None, }}',
                  f'pub const BASE_TYPE_COUNT: usize = {sum(ns == BASE_NS for ns, _ in named)};'])
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--schema", type=Path, required=True)
    args = parser.parse_args()
    inputs = args.schema.parent
    schema = read_pinned(args.schema, PIN)
    ext = read_pinned(inputs / "csipaus-ext-v1.2.xsd", "bdbbc313a7148207786c378b8c399c55edd86062a87c51f23409187c6f87f0ce")
    overlay = read_pinned(inputs / "csipaus-core-v1.2.xsd", "a6b17d65964f547586024e3033af79de7e6c07e21648ec118d93815e4cebf1aa")
    overrides = {n.attrib["name"]: list(n.iter(XSD + "element")) for n in overlay.iter(XSD + "complexType")}
    result = generate(schema, [ext], overrides)
    result = subprocess.run(["rustfmt", "--edition", "2024", "--emit", "stdout"], input=result,
                            stdout=subprocess.PIPE, text=True, check=True).stdout
    path = Path("src/model/generated.rs")
    if args.check:
        if result != path.read_text():
            parser.error("generated model is stale; rerun with the same --schema and without --check")
    else:
        path.write_text(result)
    print(f"Verified {len(schema.findall(XSD+'complexType')) + len(schema.findall(XSD+'simpleType'))} base schema types")


if __name__ == "__main__":
    main()
